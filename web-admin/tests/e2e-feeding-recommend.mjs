import { chromium } from "playwright";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const baseURL = process.env.WEB_BASE_URL || "http://127.0.0.1:5173";
const output = new URL("../artifacts/", import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } });
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
page.on("console", (message) => {
  if (message.type() === "error" && !message.text().includes("Failed to load resource")) errors.push(message.text());
});
page.on("response", (response) => {
  if (response.status() >= 400 && !response.url().endsWith("/favicon.ico"))
    errors.push(`${response.status()} ${response.url()}`);
});

await page.goto(`${baseURL}/login`, { waitUntil: "networkidle" });
await page.locator("input").nth(0).fill("admin");
await page.locator("input").nth(1).fill("123456");
await page.locator("button").filter({ hasText: "登录" }).click();
await page.waitForURL(`${baseURL}/`);
await page.goto(`${baseURL}/feeding`, { waitUntil: "networkidle" });
await page.keyboard.press("Escape");
await page.waitForTimeout(500);
await page.getByText("共 71 种", { exact: true }).waitFor();
await page.screenshot({ path: fileURLToPath(new URL("feeding-ingredients-final.png", output)), fullPage: true });
const concentrateName = `端到端精料${Date.now()}`;
await page.getByText("精料配方", { exact: true }).click();
await page.getByRole("button", { name: "生成精料" }).click();
let dialog = page.getByRole("dialog", { name: "生成精料配方" });
await dialog.waitFor();
await dialog.getByLabel("精料名称").fill(concentrateName);
for (const label of [/^玉米能量饲料$/, /^豆粕蛋白饲料$/]) await dialog.locator(".concentrate-picker .el-checkbox").filter({ hasText: label }).click();
const optimizeResponse = page.waitForResponse((response) => response.url().includes("/concentrates/optimize"));
await dialog.getByRole("button", { name: "按营养目标自动配比" }).click();
const optimized = await optimizeResponse;
if (!optimized.ok()) throw new Error(`Concentrate optimization failed: ${optimized.status()} ${await optimized.text()}`);
const optimizedBody = await optimized.json();
const optimizedRatios = optimizedBody.data.ratios.map((item) => Number(item.dryMatterRatioPct));
if (Math.abs(optimizedRatios.reduce((sum, value) => sum + value, 0) - 100) > 0.01) throw new Error("Optimized concentrate ratios do not total 100%");
if (optimizedRatios.every((value) => Math.abs(value - 50) < 0.01)) throw new Error("Optimizer returned an equal split instead of a nutrition-based solution");
await dialog.getByText("100.00%", { exact: true }).waitFor();
await dialog.getByText("每公斤精料价格", { exact: false }).waitFor();
await page.screenshot({ path: fileURLToPath(new URL("feeding-concentrate-optimization-final.png", output)), fullPage: true });
const saveResponse = page.waitForResponse((response) => response.url().endsWith("/ration-formulas") && response.request().method() === "POST");
await dialog.getByRole("button", { name: "保存精料" }).click();
if (!(await saveResponse).ok()) throw new Error("Concentrate save failed");
await dialog.waitFor({ state: "hidden" });
await page.locator(".el-overlay.el-modal-dialog").waitFor({ state: "hidden" });

await page.getByText("日粮配方", { exact: true }).click();
await page.getByRole("button", { name: "日粮配比" }).click();
dialog = page.getByRole("dialog", { name: "精料与粗料日粮配比" });
await dialog.waitFor();
await dialog.getByLabel("查看体型标准参考体重").hover();
await page.getByText("参考成年体重：大体型约 600 kg 以上；中体型约 400-600 kg。请结合品种成熟体重和生长潜力选择，不能仅按当前体重判断。", { exact: true }).waitFor();
await dialog.getByText("肥育牛", { exact: true }).click();
const numericInputs = dialog.locator(".el-input-number input");
await numericInputs.nth(0).fill("400");
await numericInputs.nth(1).fill("600");
await numericInputs.nth(2).fill("1.1");
await dialog.locator(".el-select").click();
await page.getByText(new RegExp(concentrateName)).last().click();
await dialog.getByRole("button", { name: "点击选择粗料 展开" }).click();
const ingredientPicker = page.locator(".ingredient-picker:visible");
await ingredientPicker.waitFor();
await ingredientPicker.locator(".el-checkbox__label").getByText("全株玉米青贮", { exact: true }).click();
await dialog.locator(".el-dialog__header").click();
await ingredientPicker.waitFor({ state: "hidden" }).catch(() => {});
await dialog.getByRole("button", { name: "平均分配" }).click();
await dialog.getByText("100.00%", { exact: true }).waitFor();
const responsePromise = page.waitForResponse((response) => response.url().includes("/ration-formulas/recommend"), { timeout: 10000 }).catch(() => null);
await dialog.getByRole("button", { name: "生成建议" }).click();
const recommendResponse = await responsePromise;
if (!recommendResponse) {
  const message = await page.locator(".el-message:visible").allTextContents();
  const buttonClass = await dialog.getByRole("button", { name: "生成建议" }).getAttribute("class");
  await page.screenshot({ path: fileURLToPath(new URL("feeding-recommendation-debug.png", output)), fullPage: true });
  const resources = await page.evaluate(() => performance.getEntriesByType("resource").map((entry) => entry.name).filter((name) => name.includes("feeding")));
  throw new Error(`Recommendation request was not sent. Button: ${buttonClass}. Messages: ${message.join(" | ")}. Resources: ${resources.join(" | ")}. Errors: ${errors.join(" | ")}`);
}
if (!recommendResponse.ok()) throw new Error(`Recommendation API failed: ${recommendResponse.status()} ${await recommendResponse.text()}`);
await dialog.locator(".recommend-metrics").waitFor();
await dialog.locator(".daily-supply").waitFor();
await dialog.getByText("GB/T 肥育牛 35%-50%", { exact: true }).waitFor();
await dialog.getByText("采用并继续编辑", { exact: true }).waitFor();
await page.screenshot({ path: fileURLToPath(new URL("feeding-recommendation-final.png", output)), fullPage: true });
await page.goto(`${baseURL}/feeding?tab=micronutrients`, { waitUntil: "networkidle" });
await page.keyboard.press("Escape");
await page.locator(".el-overlay").waitFor({ state: "hidden" }).catch(() => {});
await page.getByRole("button", { name: "计算需要量" }).click();
await page.getByRole("cell", { name: "钙", exact: true }).waitFor();
await page.getByText("2580", { exact: false }).first().waitFor();
await page.screenshot({ path: fileURLToPath(new URL("feeding-micronutrients-final.png", output)), fullPage: true });
await page.goto(`${baseURL}/feeding?tab=breeding`, { waitUntil: "networkidle" });
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "计算需要量" }).click();
await page.getByRole("cell", { name: "干物质采食量", exact: true }).waitFor();
await page.getByText("7.5", { exact: false }).first().waitFor();
await page.getByText("54.67%", { exact: true }).waitFor();
await page.screenshot({ path: fileURLToPath(new URL("feeding-breeding-nutrition-final.png", output)), fullPage: true });
await page.goto(`${baseURL}/feeding?tab=concentrates`, { waitUntil: "networkidle" });
const concentrateCard = page.locator(".cards article").filter({ hasText: concentrateName });
await concentrateCard.waitFor();
let statusResponse = page.waitForResponse((response) => response.url().endsWith("/activate") && response.request().method() === "POST");
await concentrateCard.getByRole("button", { name: "审核并启用" }).click();
if (!(await statusResponse).ok()) throw new Error("Formula activation failed");
await concentrateCard.getByText("已启用", { exact: true }).waitFor();
if (!(await concentrateCard.getByRole("button", { name: "删除" }).isDisabled())) throw new Error("Active formula delete button should be disabled");
statusResponse = page.waitForResponse((response) => response.url().endsWith("/deactivate") && response.request().method() === "POST");
await concentrateCard.getByRole("button", { name: "停用" }).click();
await page.getByRole("button", { name: "停用", exact: true }).last().click();
if (!(await statusResponse).ok()) throw new Error("Formula deactivation failed");
await concentrateCard.getByText("已停用", { exact: true }).waitFor();
statusResponse = page.waitForResponse((response) => response.url().endsWith("/activate") && response.request().method() === "POST");
await concentrateCard.getByRole("button", { name: "重新启用" }).click();
if (!(await statusResponse).ok()) throw new Error("Formula reactivation failed");
await concentrateCard.getByText("已启用", { exact: true }).waitFor();
statusResponse = page.waitForResponse((response) => response.url().endsWith("/deactivate") && response.request().method() === "POST");
await concentrateCard.getByRole("button", { name: "停用" }).click();
await page.getByRole("button", { name: "停用", exact: true }).last().click();
if (!(await statusResponse).ok()) throw new Error("Formula second deactivation failed");
await concentrateCard.getByText("已停用", { exact: true }).waitFor();
const deleteResponse = page.waitForResponse((response) => response.url().includes("/ration-formulas/") && response.request().method() === "DELETE");
await concentrateCard.getByRole("button", { name: "删除" }).click();
await page.getByRole("button", { name: "删除", exact: true }).last().click();
if (!(await deleteResponse).ok()) throw new Error("Formula delete failed");
await concentrateCard.waitFor({ state: "detached" });

const ingredientName = `端到端原料${Date.now()}`;
await page.getByText("原料档案", { exact: true }).click();
await page.getByRole("button", { name: "新增原料" }).click();
dialog = page.getByRole("dialog", { name: "新增原料" });
await dialog.getByLabel("原料名称").fill(ingredientName);
const ingredientCreateResponse = page.waitForResponse((response) => response.url().endsWith("/feeding/ingredients") && response.request().method() === "POST");
await dialog.getByRole("button", { name: "保存" }).click();
if (!(await ingredientCreateResponse).ok()) throw new Error("Ingredient create failed");
await dialog.waitFor({ state: "hidden" });
const ingredientRow = page.locator(".el-table__row").filter({ hasText: ingredientName });
await ingredientRow.waitFor();
const ingredientDeleteResponse = page.waitForResponse((response) => response.url().includes("/feeding/ingredients/") && response.request().method() === "DELETE");
await ingredientRow.getByRole("button", { name: "删除" }).click();
await page.getByRole("button", { name: "删除", exact: true }).last().click();
if (!(await ingredientDeleteResponse).ok()) throw new Error("Ingredient delete failed");
await ingredientRow.waitFor({ state: "detached" });

const locationSuffix = Date.now();
const barnCode = `E2E-B-${locationSuffix}`;
const barnName = `端到端栏舍${locationSuffix}`;
const herdCode = `E2E-H-${locationSuffix}`;
const herdName = `端到端牛群${locationSuffix}`;
await page.goto(`${baseURL}/locations`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: "新建栏舍" }).click();
dialog = page.getByRole("dialog", { name: "新建栏舍" });
await dialog.getByLabel("栏舍编号").fill(barnCode);
await dialog.getByLabel("栏舍名称").fill(barnName);
const barnCreateResponse = page.waitForResponse((response) => response.url().endsWith("/barns") && response.request().method() === "POST");
await dialog.getByRole("button", { name: "保存" }).click();
if (!(await barnCreateResponse).ok()) throw new Error("Barn create failed");
await dialog.waitFor({ state: "hidden" });
await page.getByRole("button", { name: "新建牛群" }).click();
dialog = page.getByRole("dialog", { name: "新建牛群" });
await dialog.getByLabel("牛群编号").fill(herdCode);
await dialog.getByLabel("牛群名称").fill(herdName);
const herdCreateResponse = page.waitForResponse((response) => response.url().endsWith("/herds") && response.request().method() === "POST");
await dialog.getByRole("button", { name: "保存" }).click();
if (!(await herdCreateResponse).ok()) throw new Error("Herd create failed");
await dialog.waitFor({ state: "hidden" });
const herdRow = page.locator(".el-table__row").filter({ hasText: herdName });
await herdRow.waitFor();
const herdDeleteResponse = page.waitForResponse((response) => response.url().includes("/herds/") && response.request().method() === "DELETE");
await herdRow.getByRole("button", { name: "删除" }).click();
await page.getByRole("button", { name: "删除", exact: true }).last().click();
if (!(await herdDeleteResponse).ok()) throw new Error("Herd delete failed");
await herdRow.waitFor({ state: "detached" });
const barnRow = page.locator(".el-table__row").filter({ hasText: barnName });
await barnRow.waitFor();
const barnDeleteResponse = page.waitForResponse((response) => response.url().includes("/barns/") && response.request().method() === "DELETE");
await barnRow.getByRole("button", { name: "删除" }).click();
await page.getByRole("button", { name: "删除", exact: true }).last().click();
if (!(await barnDeleteResponse).ok()) throw new Error("Barn delete failed");
await barnRow.waitFor({ state: "detached" });
if (errors.length) throw new Error(errors.join("\n"));
await browser.close();
console.log("Feeding E2E passed: optimization, recommendation, formula lifecycle, and safe master-data deletion");
